-- 個人トーク申請。申請者・相手の両方が承認したときだけ direct_messages を使える。
create table if not exists public.direct_chat_requests (
  id uuid primary key default gen_random_uuid(),
  requester_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  requester_approved boolean not null default false,
  recipient_approved boolean not null default false,
  status text not null default 'pending' check (status in ('pending','accepted','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (requester_id <> recipient_id)
);
create index if not exists direct_chat_requests_recipient_idx on public.direct_chat_requests(recipient_id,status);
alter table public.direct_chat_requests enable row level security;
drop policy if exists "Participants can read requests" on public.direct_chat_requests;
create policy "Participants can read requests" on public.direct_chat_requests for select to authenticated using (auth.uid()=requester_id or auth.uid()=recipient_id);
drop policy if exists "Users can create requests" on public.direct_chat_requests;
create policy "Users can create requests" on public.direct_chat_requests for insert to authenticated with check (auth.uid()=requester_id and status='pending' and requester_approved=false and recipient_approved=false);
drop policy if exists "No direct client updates to requests" on public.direct_chat_requests;
create policy "No direct client updates to requests" on public.direct_chat_requests for update to authenticated using (false) with check (false);

create or replace function public.request_direct_chat(target_user uuid)
returns uuid language plpgsql security definer set search_path=public,auth as $$
declare req_id uuid;
begin
  if auth.uid() is null or auth.uid()=target_user then raise exception '相手を確認してください'; end if;
  if not exists(select 1 from public.profiles where id=target_user) then raise exception 'ユーザーが見つかりません'; end if;
  select id into req_id from public.direct_chat_requests
   where ((requester_id=auth.uid() and recipient_id=target_user) or (requester_id=target_user and recipient_id=auth.uid()))
   and status in ('pending','accepted') order by created_at desc limit 1;
  if req_id is not null then return req_id; end if;
  insert into public.direct_chat_requests(requester_id,recipient_id) values(auth.uid(),target_user) returning id into req_id;
  return req_id;
end $$;

create or replace function public.approve_direct_chat_request(request_id uuid)
returns text language plpgsql security definer set search_path=public,auth as $$
declare r public.direct_chat_requests%rowtype;
begin
  select * into r from public.direct_chat_requests where id=request_id for update;
  if not found then raise exception '申請が見つかりません'; end if;
  if auth.uid() not in (r.requester_id,r.recipient_id) then raise exception 'この申請を承認できません'; end if;
  if r.status='rejected' then raise exception 'この申請は拒否されています'; end if;
  if auth.uid()=r.requester_id then update public.direct_chat_requests set requester_approved=true,updated_at=now() where id=request_id returning * into r;
  else update public.direct_chat_requests set recipient_approved=true,updated_at=now() where id=request_id returning * into r; end if;
  if r.requester_approved and r.recipient_approved then
    update public.direct_chat_requests set status='accepted',updated_at=now() where id=request_id;
    return 'accepted';
  end if;
  return 'pending';
end $$;
grant execute on function public.request_direct_chat(uuid) to authenticated;
grant execute on function public.approve_direct_chat_request(uuid) to authenticated;

-- 既存の個人メッセージ送信は、相互承認済みの相手だけに限定
drop policy if exists "Users can send direct messages as themselves" on public.direct_messages;
create policy "Users can send direct messages as themselves" on public.direct_messages for insert to authenticated
with check (
  auth.uid()=sender_id and exists (
    select 1 from public.direct_chat_requests r
    where r.status='accepted'
      and r.requester_approved and r.recipient_approved
      and ((r.requester_id=sender_id and r.recipient_id=recipient_id)
        or (r.requester_id=recipient_id and r.recipient_id=sender_id))
  )
);

drop policy if exists "Users can read their direct messages" on public.direct_messages;
create policy "Users can read their direct messages" on public.direct_messages for select to authenticated
using (
  (auth.uid()=sender_id or auth.uid()=recipient_id)
  and exists (
    select 1 from public.direct_chat_requests r
    where r.status='accepted' and r.requester_approved and r.recipient_approved
      and ((r.requester_id=sender_id and r.recipient_id=recipient_id)
        or (r.requester_id=recipient_id and r.recipient_id=sender_id))
  )
);

grant select, insert on public.global_chat_messages to authenticated;
grant select, insert on public.direct_chat_requests to authenticated;
grant select, insert on public.direct_messages to authenticated;
